export const smallGlyph = ch => S[ch] ?? S[ch.toUpperCase()] ?? S[' '];
export const glyph = ch => G[ch] ?? G[ch.toUpperCase()] ?? G[' '];
export const textWidth = (s, scale = 1) => (String(s).length * 6 - 1) * scale;

// Draw text with fillRect pixels (for the playfield, not the dot-matrix strip).
export function drawText(ctx, str, x, y, color, { scale = 1, align = 'left' } = {}) {
  const s = String(str);
  let cx = align === 'center' ? Math.round(x - textWidth(s, scale) / 2) : align === 'right' ? x - textWidth(s, scale) : x;
  ctx.fillStyle = color;
  for (const ch of s) {
    const rows = glyph(ch);
    for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (rows[r] & (0x10 >> c)) ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
    cx += 6 * scale;
  }
}

export const commas = n => String(Math.floor(n)).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
